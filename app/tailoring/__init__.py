"""Tailoring (ADV4): adapt one rendition to one destination, deterministically, and say what changed.

    tailor(rendition, destination, surface_spec, ruleset) -> TailoredRendition(.rendition, .diff, .warnings)

Steps, in order:
  1. remove links the rules or spec do not allow           (LINK_REMOVED)
  2. apply the profile: forum | article | slack | newsletter | mrss | generic (see profiles.py)
  3. drop media the destination does not accept            (MEDIA_DROPPED, CONTENT_TYPE_CHANGED)
  4. fit tags to tag_max / tag_pattern                     (TAGS_CHANGED)
  5. add the AI disclosure when the rules require it       (AI_DISCLOSURE_APPENDED)
  6. fit the title, then the body, at safe boundaries      (TITLE_TRUNCATED, BODY_TRUNCATED)
  7. re-check the spec; anything still wrong is returned in .violations and as SPEC_UNRESOLVED warnings

Tailoring never hides a change: every edit adds a warning, and .diff lists before/after per field.
It does not use an LLM, so it does not make the content AI-generated by itself.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from app.contract.models import Destination, Rendition, Violation
from app.rules.disclosure import content_language
from app.rules.gate import resolve_ruleset
from app.rules.links import url_host
from app.rules.models import RuleSet
from app.rules.spec import check_spec, effective_spec
from app.tailoring.draft import Draft
from app.tailoring.fit import add_disclosure, apply_link_policy, fit_body, fit_media, fit_tags, fit_title
from app.tailoring.profiles import (
    MENTION_PLATFORMS,
    PLATFORM_SPEC_DEFAULTS,
    PROFILES,
    TITLE_NEEDED,
    adapt_mentions,
    choose_profile,
    platform_of,
)
from app.tailoring.textops import link_keeper
from app.tailoring.truncate import truncate_words

_DIFF_FIELDS = (
    "title",
    "body",
    "body_format",
    "content_type",
    "link_url",
    "canonical_url",
    "tags",
    "media",
    "mentions",
)


@dataclass
class TailoredRendition:
    rendition: Rendition
    diff: list[dict[str, Any]]
    warnings: list[str]
    violations: list[Violation] = field(default_factory=list)  # still unfit after tailoring (empty = ok)
    profile: str = "generic"

    @property
    def ok(self) -> bool:
        return not self.violations


def tailor(
    rendition: Rendition | dict[str, Any],
    destination: Destination | dict[str, Any],
    surface_spec: dict[str, Any] | None,
    ruleset: RuleSet | dict[str, Any] | None = None,
) -> TailoredRendition:
    original = rendition if isinstance(rendition, Rendition) else Rendition.model_validate(rendition)
    dest = destination if isinstance(destination, Destination) else Destination.model_validate(destination)
    if ruleset is None:
        rules, _source = resolve_ruleset(dest)  # inline rules + Appendix A record fields
    else:
        rules = ruleset if isinstance(ruleset, RuleSet) else RuleSet.model_validate(ruleset)
        if not rules.languages and dest.language:
            rules = RuleSet.for_destination({"rules": rules, "language": dest.language})
    platform = platform_of(dest)
    spec = {**PLATFORM_SPEC_DEFAULTS.get(platform, {}), **effective_spec(surface_spec, dest.spec_overrides)}
    profile = choose_profile(dest)

    draft = Draft(
        rendition=original.model_copy(deep=True), lang=content_language(original), instance_host=instance_host(dest)
    )
    if rules is None:
        draft.warn("NO_RULES", "destination has no confirmed rules; only format tailoring was applied")
    keep_links = link_keeper(
        rules.link_policy if rules else "any",
        rules.link_allowlist if rules else [],
        spec.get("links_allowed") is not False,
    )

    apply_link_policy(draft, rules, spec)
    PROFILES[profile](draft, platform, spec)
    if platform in MENTION_PLATFORMS:
        adapt_mentions(draft, platform)
    fit_media(draft, spec, keep_links)
    fit_tags(draft, spec)
    add_disclosure(draft, rules)
    fit_title(draft, spec, profile in TITLE_NEEDED)
    disclosure_fits = fit_body(draft, spec)

    final = draft.build()
    violations = check_spec(final, spec)
    if not disclosure_fits:
        violations.append(
            Violation(field="body", rule="disclosure", message="required AI disclosure does not fit the body limit")
        )
    for v in violations:
        draft.warn("SPEC_UNRESOLVED", f"{v.field}: {v.message}")
    return TailoredRendition(final, _diff(original, final), draft.warnings, violations, profile)


def instance_host(dest: Destination) -> str | None:
    """Host of the destination's instance (community_url / base_url / url), without port."""
    values = [v for v in dest.instance.values() if isinstance(v, str)] + [dest.url or ""]
    for value in values:
        if "://" not in value and "." not in value:
            continue  # a plain name like {"community": "video"} is not a host
        host = url_host(value)
        if host:
            return host
    return None


def _value(r: Rendition, name: str) -> Any:
    value = getattr(r, name)
    return [m.url for m in value] if name == "media" else value


def _diff(before: Rendition, after: Rendition) -> list[dict[str, Any]]:
    changes = []
    for name in _DIFF_FIELDS:
        old, new = _value(before, name), _value(after, name)
        if old != new:
            changes.append({"field": name, "before": old, "after": new})
    return changes


