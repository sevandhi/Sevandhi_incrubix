"""Load check: N parallel contract publishes against a running stack must never give a 500.

    uv run python scripts/load_publish.py --api http://127.0.0.1:8088 --token "$API_TOKEN" --mock http://127.0.0.1:8089 \
        [--n 40] [--connector discourse] [--out evidence/integration/M6_parallel_publish.txt]

Each publish has its own idempotency key and goes to one fresh mock-platforms forum, then the same N requests
are sent again (all must replay, no new post). The platform's own counter must show exactly N creates.
"""

from __future__ import annotations

import argparse
import asyncio
import collections
import os
import sys
import time
import uuid
from pathlib import Path

import httpx


def _label(response: object) -> str:
    """'200', or '<status> <error code>' (e.g. '429 PLATFORM_RATE_LIMIT'), or the transport exception name."""
    if not isinstance(response, httpx.Response):
        return type(response).__name__
    if response.status_code == 200:
        return "200"
    try:
        return f"{response.status_code} {response.json()['error']['code']}"
    except (ValueError, KeyError, TypeError):
        return str(response.status_code)


async def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api", default=os.environ.get("IBX_API_URL", "http://127.0.0.1:8088"))
    parser.add_argument("--token", default=os.environ.get("IBX_API_TOKEN", "ibx-dev-token"))
    parser.add_argument("--mock", default=os.environ.get("IBX_MOCK_URL", "http://127.0.0.1:8089"))
    parser.add_argument("--n", type=int, default=40)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    tenant = f"load-{uuid.uuid4().hex[:8]}"

    def body(i: int) -> dict:
        return {
            "rendition": {"title": f"Load test topic number {i} for the forum", "body": "Parallel publish load test body text."},
            "destination": {"connector_key": "discourse", "surface": "topic", "url": f"http://mock-platforms:8080/discourse/{tenant}"},
            "connection": {"connector_key": "discourse"},
            "idempotency_key": f"{tenant}-{i}",
        }

    headers = {"Authorization": f"Bearer {args.token}"}
    lines = [f"# generated by scripts/load_publish.py at {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}",
             f"# API {args.api}, {args.n} parallel contract publishes (distinct keys) to mock forum {tenant}, then a replay round"]
    ok = True
    async with httpx.AsyncClient(base_url=args.api, headers=headers, timeout=120) as client:
        for label in ("first round", "replay round"):
            started = time.perf_counter()
            responses = await asyncio.gather(*[client.post("/connector/v1/discourse/publish", json=body(i)) for i in range(args.n)],
                                             return_exceptions=True)
            elapsed = time.perf_counter() - started
            statuses = collections.Counter(_label(r) for r in responses)
            replayed = sum(1 for r in responses if isinstance(r, httpx.Response) and r.headers.get("Idempotent-Replayed") == "true")
            lines.append(f"{label}: statuses {dict(statuses)}, replayed {replayed}, wall time {elapsed:.2f}s")
            ok = ok and statuses == collections.Counter({"200": args.n})
    counts = httpx.get(f"{args.mock}/_counts", params={"platform": "discourse", "tenant": tenant}).json()["counts"]
    creates = sum(v for k, v in counts.get("discourse", {}).get(tenant, {}).items() if k.startswith("POST") and "posts" in k)
    lines.append(f"platform creates counted by the mock: {creates} (expected {args.n})")
    ok = ok and creates == args.n
    lines.append("RESULT: PASS (no 500, every publish 200, one post per key)" if ok else "RESULT: FAIL")
    text = "\n".join(lines) + "\n"
    print(text, end="")
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
