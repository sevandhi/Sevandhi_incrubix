"""Generate evidence/LEDGER.md from evidence/ledger.yaml and the proof results of this run (evidence/proof_runs/*.json).

    uv run python scripts/prove_ledger.py [--run-id RUN]       (prove_all.sh passes its run id)

Status rules (the skill's "Yes only when a script reproduces it"):
  * a row's status is the status its proof reported (Yes / Partial / No);
  * with --run-id, a proof from another run counts as "not run in this run" -> No;
  * "cap: Partial" lowers a Yes to Partial (the note says why); a row with no proof is No (the note says why);
  * declaration rows are for the human.
Evidence paths that do not exist are flagged "(missing)".
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "evidence/proof_runs"


def load_proof(pid: str) -> dict | None:
    path = RUNS / f"{pid}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-id", default=None)
    parser.add_argument("--ledger", type=Path, default=ROOT / "evidence/ledger.yaml")
    parser.add_argument("--out", type=Path, default=ROOT / "evidence/LEDGER.md")
    args = parser.parse_args(argv)
    rows = yaml.safe_load(args.ledger.read_text(encoding="utf-8"))["rows"]
    lines = ["# Evidence ledger", "",
             "Generated by `scripts/prove_ledger.py` from `evidence/ledger.yaml` and the proof results in `evidence/proof_runs/`."
             " Do not edit by hand: re-run `scripts/prove_all.sh`.", ""]
    used_runs: set[str] = set()
    counts: dict[str, int] = {}
    table = ["| ID | Form tab / row | Claim | Status | Evidence | Reproduce | Why not Yes / notes |", "|---|---|---|---|---|---|---|"]
    for row in rows:
        reasons: list[str] = []
        if row.get("human"):
            status = "Human"
        elif not row.get("proof"):
            status, reasons = "No", [row.get("note", "no proof script")]
        else:
            pid, _, sub = str(row["proof"]).partition("#")
            proof = load_proof(pid)
            if proof is None:
                status, reasons = "No", [f"proof {pid} has not been run" + (f"; {row['note']}" if row.get("note") else "")]
            elif args.run_id and proof.get("run_id") != args.run_id:
                status, reasons = "No", [f"proof {pid} did not run in this run ({proof.get('run_id')} != {args.run_id})"]
            else:
                used_runs.add(f"{pid}: {proof.get('finished_at')} ({proof.get('mode')})")
                if sub:
                    item = (proof.get("sub") or {}).get(sub)
                    status, reasons = (item["status"], item["reasons"]) if item else ("No", [f"{pid} has no result for {sub}"])
                else:
                    status, reasons = proof["status"], proof.get("reasons", [])
                if row.get("cap") and status == "Yes":
                    status = row["cap"]
                if row.get("note") and status != "Yes":
                    reasons = [*reasons, row["note"]]
        counts[status] = counts.get(status, 0) + 1
        evidence = []
        for path in row.get("evidence") or []:
            exists = (ROOT / path).exists()
            evidence.append(f"`{path}`" + ("" if exists else " (missing)"))
        why = "; ".join(r[:220] for r in reasons[:4]) + (f" (+{len(reasons) - 4} more)" if len(reasons) > 4 else "")
        table.append(f"| {row['id']} | {cell(row['tab'])} #{cell(row['row'])} | {cell(row['claim'])} | **{status}** | "
                     f"{'<br>'.join(evidence) or '-'} | `{cell(row['reproduce'])}` | {cell(why or row.get('note', ''))} |")
    lines.append("Status counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".")
    if args.run_id:
        lines.append(f"Run id: `{args.run_id}`.")
    lines += ["", *table, "", "## Proof results used", "", *[f"- {u}" for u in sorted(used_runs)], ""]
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT)}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
