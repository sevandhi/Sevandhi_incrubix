"""E2E against a running compose stack in simulation mode (plan §10). Skipped unless IBX_E2E_API_URL is set.

    COMPOSE_PROJECT_NAME=ibx_e2e SIMULATION_MODE=true IBX_API_PORT=18088 IBX_MOCK_PORT=18089 \\
        PUBLIC_BASE_URL=http://127.0.0.1:18088 docker compose up -d --build --wait
    IBX_E2E_API_URL=http://127.0.0.1:18088 IBX_E2E_TOKEN=ibx-dev-token IBX_E2E_COMPOSE_PROJECT=ibx_e2e \\
        IBX_E2E_EVIDENCE_DIR=evidence/must_haves uv run pytest -q tests/e2e

``IBX_E2E_EVIDENCE_DIR`` (optional) makes the tests write their request/response logs there as evidence.
"""

from __future__ import annotations

import json
import os
import re
import time
import uuid
from pathlib import Path
from typing import Any

import httpx
import pytest

API = os.environ.get("IBX_E2E_API_URL")
TOKEN = os.environ.get("IBX_E2E_TOKEN", "ibx-dev-token")


class Stack:
    def __init__(self, client: httpx.Client) -> None:
        self.client = client
        self.log: list[str] = []
        self.run_tag = uuid.uuid4().hex[:8]

    def call(self, method: str, path: str, **kwargs: Any) -> httpx.Response:
        response = self.client.request(method, path, **kwargs)
        from app.reliability.redact import redact

        body = redact(kwargs.get("json")) if "json" in kwargs else (kwargs.get("content") or b"")
        if isinstance(body, bytes):
            body = body.decode(errors="replace")
        self.log.append(f"> {method} {path}\n{json.dumps(body, indent=1) if not isinstance(body, str) else body}\n"
                        f"< {response.status_code}\n{response.text[:4000]}\n")
        return response

    def job(self, job_id: str, timeout_s: float = 120) -> dict[str, Any]:
        deadline = time.time() + timeout_s
        while time.time() < deadline:
            job = self.client.get(f"/api/v1/jobs/{job_id}").json()
            if job["status"] in ("succeeded", "failed"):
                self.log.append(f"< job {job_id}: {json.dumps(job)[:3000]}\n")
                return job
            time.sleep(0.5)
        raise AssertionError(f"job {job_id} did not finish in {timeout_s}s")

    def certify(self, destination_id: str) -> dict[str, Any]:
        started = self.call("POST", "/api/v1/certifications", json={"destination_id": destination_id})
        assert started.status_code == 202, started.text
        self.job(started.json()["job_id"])
        return self.call("GET", started.json()["run_url"]).json()

    def write_evidence(self, name: str) -> None:
        folder = os.environ.get("IBX_E2E_EVIDENCE_DIR")
        if folder:
            path = Path(folder) / name
            path.parent.mkdir(parents=True, exist_ok=True)
            text = "\n".join(self.log)
            text = re.sub(r"(sig=)[0-9a-f]+", r"\1***", text)  # signed links are short-lived credentials
            path.write_text(f"# generated by tests/e2e ({time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}), API {API}\n"
                            "# signed-link signatures are masked (sig=***)\n\n" + text, encoding="utf-8")


@pytest.fixture
def stack() -> Any:
    if not API:
        pytest.skip("IBX_E2E_API_URL is not set: the e2e suite needs a running compose stack")
    with httpx.Client(base_url=API, headers={"Authorization": f"Bearer {TOKEN}"}, timeout=60) as client:
        try:
            ready = client.get("/ready")
        except httpx.HTTPError:
            pytest.skip(f"no stack at {API}")
        if ready.status_code != 200:
            pytest.skip(f"stack at {API} is not ready: {ready.text[:200]}")
        yield Stack(client)
