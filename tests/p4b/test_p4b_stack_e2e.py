"""ADV2 + ADV4 on a running compose stack in LOCAL mode (real Lemmy) with the local LLM (compose profile ``llm``).
Skipped unless IBX_P4B_E2E_API_URL is set.

    COMPOSE_PROJECT_NAME=ibx_p4b SIMULATION_MODE=false IBX_API_PORT=18488 IBX_MOCK_PORT=18489 \\
      IBX_BOOTSTRAP_OUT_UID=10001 IBX_BOOTSTRAP_OUT_GID=10001 LLM_PROVIDER=openai_compat \\
      LLM_MODEL=qwen2.5:1.5b-instruct PUBLIC_BASE_URL=http://127.0.0.1:18488 \\
      docker compose --profile llm up -d --build --wait
    IBX_P4B_E2E_API_URL=http://127.0.0.1:18488 COMPOSE_PROJECT_NAME=ibx_p4b IBX_P4B_EXPECT_PROVIDER=ollama \\
      IBX_P4B_EVIDENCE_DIR=evidence/advanced uv run pytest -q tests/p4b/test_p4b_stack_e2e.py

Flow: write rules into the REAL local Lemmy community sidebar -> one catalogue row -> POST rules/capture (platform
API: Lemmy sidebar) -> the LLM proposes, quotes are verified -> confirm page -> a person confirms -> certification
-> a promotional post is refused by the confirmed rules, a normal post is published on Lemmy, the next one waits for
the weekly cap. Then POST /api/v1/tailorings for the same destination.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import time
from pathlib import Path
from typing import Any

import httpx
import pytest

API = os.environ.get("IBX_P4B_E2E_API_URL")
TOKEN = os.environ.get("IBX_P4B_E2E_TOKEN", "ibx-dev-token")
ROOT = Path(__file__).resolve().parents[2]
COMMUNITY = "ibx_test_2"
SIDEBAR = (
    "Welcome to the IncuBrix local test community.\n\n"
    "**Rules**\n\n"
    "1. Self-promotion is not allowed.\n"
    "2. Each member may make one post per week.\n"
    "3. Bots and automated posting tools are allowed if they follow these rules.\n"
    "4. Posts must be written in English.\n"
    "5. AI-generated content must be clearly labelled.\n"
)

pytestmark = pytest.mark.skipif(not API, reason="IBX_P4B_E2E_API_URL is not set: needs the compose stack")
LOG: list[str] = []


def in_stack(code: str) -> Any:
    result = subprocess.run(["docker", "compose", "exec", "-T", "api", "python", "-c", code], cwd=ROOT,
                            capture_output=True, text=True, timeout=120, check=False)
    assert result.returncode == 0, result.stderr[-2000:]
    return json.loads(result.stdout.strip().splitlines()[-1])


def call(client: httpx.Client, method: str, path: str, **kw: Any) -> httpx.Response:
    response = client.request(method, path, **kw)
    body = kw.get("json")
    LOG.append(f"> {method} {path}\n{json.dumps(body, indent=1) if body is not None else ''}\n< {response.status_code}\n"
               f"{response.text[:3000]}\n")
    return response


def job(client: httpx.Client, job_id: str, timeout_s: float = 900) -> dict[str, Any]:
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        data = client.get(f"/api/v1/jobs/{job_id}").json()
        if data["status"] in ("succeeded", "failed"):
            LOG.append(f"< job {job_id}: {json.dumps(data)[:3000]}\n")
            return data
        time.sleep(1)
    raise AssertionError(f"job {job_id} did not finish")


def write_evidence(name: str) -> None:
    folder = os.environ.get("IBX_P4B_EVIDENCE_DIR")
    if folder:
        path = ROOT / folder / name
        path.parent.mkdir(parents=True, exist_ok=True)
        text = re.sub(r"(sig=)[0-9a-f]+", r"\1***", "\n".join(LOG))
        path.write_text(f"# generated by tests/p4b/test_p4b_stack_e2e.py at {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}"
                        f", API {API}\n# signed-link signatures masked (sig=***)\n\n{text}", encoding="utf-8")


@pytest.fixture
def client() -> Any:
    with httpx.Client(base_url=API or "", headers={"Authorization": f"Bearer {TOKEN}"}, timeout=60) as c:
        if c.get("/ready").status_code != 200:
            pytest.skip("stack not ready")
        yield c


def test_capture_from_real_lemmy_sidebar_confirm_and_enforce(client: httpx.Client) -> None:
    LOG.clear()
    edited = in_stack(
        "import json, httpx; d = json.load(open('/bootstrap/out/lemmy.json')); h = {'Authorization': 'Bearer ' + d['jwt']};"
        f" cid = d['communities']['{COMMUNITY}'];"
        f" r = httpx.put(d['base_url'] + '/api/v3/community', json={{'community_id': cid, 'description': {SIDEBAR!r}}}, headers=h);"
        " print(json.dumps(r.status_code))")
    assert edited == 200
    LOG.append(f"# real Lemmy sidebar of c/{COMMUNITY} set to:\n{SIDEBAR}")
    row = {"name": "Local Lemmy rules capture", "url": f"http://lemmy:8536/c/{COMMUNITY}", "connector_key": "lemmy",
           "language": "en", "category": "test"}
    created = call(client, "POST", "/api/v1/destinations", json=row)
    assert created.status_code in (200, 201), created.text
    dest_id = created.json()["destination_id"]

    started = call(client, "POST", f"/api/v1/destinations/{dest_id}/rules/capture", json={"use_platform_api": True})
    assert started.status_code == 202, started.text
    done = job(client, started.json()["job_id"])
    assert done["status"] == "succeeded", done
    result = done["result"]
    expected = os.environ.get("IBX_P4B_EXPECT_PROVIDER")
    if expected:
        assert result["provider"] == expected, result
    manifest = httpx.get(result["links"]["manifest"], timeout=30).json()
    llm = [p for p in manifest["providers"] if p["name"] == "llm"][0]
    LOG.append(f"# manifest providers: {json.dumps(manifest['providers'])}\n# manifest cost: {json.dumps(manifest['cost'])}\n")
    assert llm["cost_usd"] == 0.0 and "fallback_used" in llm and llm["tokens"]["total"] >= 0

    proposal = call(client, "GET", f"/api/v1/rule-proposals/{result['proposal_id']}").json()
    assert proposal["status"] == "proposed" and proposal["sources"][0]["kind"] == "lemmy_sidebar"
    for field in proposal["fields"]:
        if field["status"] == "verified":
            assert field["quote"] and re.sub(r"\s+", " ", field["quote"]).strip() in re.sub(r"\s+", " ", SIDEBAR)
    page = client.get(proposal["ui_url"])
    assert page.status_code == 200 and "Confirm posting rules" in page.text
    LOG.append(f"> GET {proposal['ui_url']}\n< {page.status_code} text/html ({len(page.text)} bytes)\n")

    # not used before a person confirms
    content = {"title": "How do you test long-tail communities?", "body": "We compared three ways of testing community "
               "posts. What has worked for you?", "ai_generated": False, "is_promotional": False, "language": "en"}
    before = call(client, "POST", "/api/v1/publications", json={"destination_id": dest_id, "content": content})
    assert before.status_code == 409 and before.json()["error"]["code"] == "DEST_RULES_UNCONFIRMED"

    # the person checks the quotes and corrects what the model got wrong (any field may be edited)
    overrides = {"self_promo": "disallowed", "frequency_cap": "1/P7D", "automation_allowed": True}
    confirmed = call(client, "POST", f"/api/v1/rule-proposals/{result['proposal_id']}/confirm",
                     json={"confirmed_by": "e2e-reviewer", "overrides": overrides, "note": "checked against the sidebar"})
    assert confirmed.status_code == 200, confirmed.text
    edited_fields = confirmed.json()["rules"]["rules"]
    LOG.append(f"# fields the reviewer changed: "
               f"{sorted(k for k, v in overrides.items() if proposal['rules'].get(k) != v)}\n")
    assert edited_fields["self_promo"] == "disallowed"

    cert = call(client, "POST", "/api/v1/certifications", json={"destination_id": dest_id})
    assert cert.status_code == 202
    job(client, cert.json()["job_id"], 300)

    promo = call(client, "POST", "/api/v1/publications", json={"destination_id": dest_id, "content": {
        **content, "title": "Our new tool is live", "body": "Sign up today at https://mytool.example.com/?utm_source=lemmy",
        "is_promotional": True, "owner_domains": ["mytool.example.com"]}})
    assert promo.status_code == 409 and promo.json()["error"]["code"] == "DEST_RULE_SELF_PROMO"
    first = call(client, "POST", "/api/v1/publications", json={"destination_id": dest_id, "content": content})
    assert first.status_code == 202, first.text
    job(client, first.json()["job_id"], 300)
    published = call(client, "GET", first.json()["publication_url"]).json()
    assert published["state"] == "published" and published["live_url"]
    second = call(client, "POST", "/api/v1/publications", json={"destination_id": dest_id, "content": {
        **content, "title": "A second question this week?"}})
    assert second.status_code == 202 and second.json()["publication"]["state"] == "rescheduled"
    call(client, "POST", f"/api/v1/publications/{published['publication_id']}/delete")  # tidy the real Lemmy post

    tailored = call(client, "POST", "/api/v1/tailorings", json={"destination_ids": [dest_id], "content": {
        "title": "We built a video tool #ai #video", "body": "Here is what we learned. Subscribe for more!\n\nWhat would "
        "you test first?", "canonical_url": "https://blog.example.com/post", "tags": ["ai", "video"], "ai_generated": True,
        "language": "en"}})
    assert tailored.status_code == 202
    tail = job(client, tailored.json()["job_id"], 120)
    assert tail["status"] == "succeeded" and tail["result"]["tailorings"][0]["diff"]
    write_evidence("ADV2_proposal_confirm.log")
